"""Optional authenticated Nightshift narrative, never a substitute for cited evidence."""

import json
import os


def request_nightshift_insight(investigation: dict) -> dict:
    """Request a supplemental narrative; fail closed when runtime is unavailable."""
    if os.getenv("XAI_ENABLE_NIGHTSHIFT", "").lower() not in {"1", "true", "yes"}:
        return {"status": "disabled", "used": False}

    token = os.getenv("METERLESS_RUNTIME_TOKEN", "")
    if not token:
        return {"status": "not_configured", "used": False}

    from openai import OpenAI

    model = os.getenv("METERLESS_MODEL", "meterless/auto")
    client = OpenAI(
        api_key=token,
        base_url=os.getenv("METERLESS_BASE_URL", "http://127.0.0.1:8088/v1"),
        default_headers={"meterless-app": "careerbridge-xai", "meterless-scope": "user"},
        timeout=20.0,
        max_retries=0,
    )
    payload = {
        "question": investigation["question"],
        "candidate_goal": investigation["candidate_goal"],
        "conclusion": investigation["conclusion"],
        "source_critique": investigation["source_critique"],
        "priority_skill_gaps": investigation["priority_skill_gaps"][:5],
        "boundaries": investigation["boundaries"],
    }
    try:
        completion = client.chat.completions.create(
            model=model,
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You summarize only the structured career evidence provided. "
                        "Never claim to know why an employer rejected a candidate. "
                        "Do not add jobs, sources, counts, skills or facts. "
                        "Explicitly identify sample or unverified evidence. "
                        "Your text is advisory, not a verified finding. Respond briefly."
                    ),
                },
                {"role": "user", "content": json.dumps(payload)},
            ],
            max_tokens=230,
        )
        text = completion.choices[0].message.content if completion.choices else None
        if not isinstance(text, str) or not text.strip():
            return {"status": "empty_response", "used": False, "model_requested": model}
        return {
            "status": "success", "used": True, "model_requested": model,
            "model_reported": getattr(completion, "model", None),
            "advisory_narrative": text.strip(),
            "independently_verified": False,
            "disclaimer": "Narrative generated by AI; use structured cited findings for evidence.",
        }
    except Exception as exc:
        status_code = getattr(exc, "status_code", None)
        return {
            "status": "authentication_failed" if status_code == 401 else "runtime_unavailable",
            "used": False,
            "model_requested": model,
            # Never include raw exception strings or credentials in the API or logs.
        }
